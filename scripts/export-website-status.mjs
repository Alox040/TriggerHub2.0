import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const sourcePath = path.join(repoRoot, "project-context", "website-status.json");
const targetPath = path.join(repoRoot, "website", "src", "data", "projectStatus.ts");

const requiredStringFields = [
  "productName",
  "statusLabel",
  "statusDescription",
  "updatedAt",
];

const requiredArrayFields = [
  "availableNow",
  "inProgress",
  "planned",
  "proofPoints",
  "limitations",
  "featureSections",
];

function assertSchema(data) {
  for (const field of requiredStringFields) {
    if (typeof data[field] !== "string" || data[field].trim() === "") {
      throw new Error(`Invalid or missing string field: ${field}`);
    }
  }

  for (const field of requiredArrayFields) {
    if (!Array.isArray(data[field])) {
      throw new Error(`Invalid or missing array field: ${field}`);
    }
  }

  for (const key of ["availableNow", "inProgress", "planned", "proofPoints", "limitations"]) {
    if (!data[key].every((item) => typeof item === "string" && item.trim() !== "")) {
      throw new Error(`Field ${key} must contain only non-empty strings`);
    }
  }

  for (const section of data.featureSections) {
    if (
      typeof section !== "object" ||
      section === null ||
      typeof section.title !== "string" ||
      typeof section.description !== "string" ||
      !Array.isArray(section.items) ||
      !section.items.every((item) => typeof item === "string" && item.trim() !== "")
    ) {
      throw new Error("Invalid featureSections entry");
    }
  }
}

function buildTargetFile(jsonObject) {
  const payload = JSON.stringify(jsonObject, null, 2);
  return `/* eslint-disable */
// This file is generated by scripts/export-website-status.mjs.
// Source of truth: project-context/website-status.json.
// Do not edit manually.

export type ProjectStatus = {
  productName: string;
  statusLabel: string;
  statusDescription: string;
  updatedAt: string;
  availableNow: string[];
  inProgress: string[];
  planned: string[];
  proofPoints: string[];
  limitations: string[];
  featureSections: Array<{
    title: string;
    description: string;
    items: string[];
  }>;
};

export const projectStatus: ProjectStatus = ${payload} as const;
`;
}

async function main() {
  const raw = await readFile(sourcePath, "utf8");
  const data = JSON.parse(raw);
  assertSchema(data);

  const output = buildTargetFile(data);
  await writeFile(targetPath, output, "utf8");
  console.log(`Exported website status to ${path.relative(repoRoot, targetPath)}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
